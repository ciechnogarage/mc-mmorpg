'use strict'
// Sonda zaklec: bot rzuca zaklecie w kukle; stan swiata mierzy RCON (konsola tylko obserwuje + rozdaje).
const mineflayer = require('mineflayer')
const { Rcon } = require('rcon-client')
const rp = require('./resourcepack')
const HOST = process.env.MC_HOST || 'zaklecia-proba'
const ZAK = process.argv[2] || 'ZAKLECIE_PLOMIENIE'
const TRZYMAJ = +(process.argv[3] || 3000)
const sleep = ms => new Promise(r => setTimeout(r, ms))
const clean = s => String(s).replace(/§./g, '').replace(/\x1b\[[0-9;]*m/g, '').trim()
;(async () => {
  const rcon = await Rcon.connect({ host: HOST, port: 25575, password: process.env.RCON_PASS || 'zaklecia' })
  const cmd = async c => clean(await rcon.send(c))
  const bot = mineflayer.createBot({ host: HOST, port: 25565, username: 'MagTest', version: '1.21.11' })
  bot._client.on('add_resource_pack', () => {}); rp.attach(bot._client)
  const czat = []; bot.on('messagestr', m => czat.push(m))
  const czastki = {}; const probki = []; const dal = []; bot._client.on('world_particles', p => { const k = p.particle?.type ?? p.particleId ?? '?'; czastki[k] = (czastki[k] || 0) + 1; if (bot.entity && (k==='flame'||k==='snowflake') && (p.amount===4||p.amount===3)) dal.push(Math.hypot(p.x-bot.entity.position.x, p.z-bot.entity.position.z)); if ((k==='flame') && probki.length < 6) probki.push({k, x:(p.x-bot.entity.position.x).toFixed(2), y:(p.y-bot.entity.position.y).toFixed(2), z:(p.z-bot.entity.position.z).toFixed(2), off:[p.offsetX,p.offsetY,p.offsetZ].map(v=>(+v).toFixed(2)), v:(+(p.velocityOffset ?? p.particleData ?? p.speed ?? 0)).toFixed?.(2), n:p.amount ?? p.particles, raw:Object.keys(p).join(',')}) })
  await new Promise(r => bot.once('spawn', r)); await sleep(2500)
  console.log('klasa/mana start:', await cmd('papi parse MagTest %mmocore_class% %mmocore_mana%/%mmocore_max_mana%'))
  await cmd('minecraft:clear MagTest'); await cmd('mmocore admin resource-mana set MagTest 100'); await cmd('minecraft:kill @e[type=zombie]')
  await cmd('minecraft:tp MagTest 0 -60 0 0 0')
  await cmd('mm mobs spawn ZAK_KUKLA 1 world,0.5,-60,4.5')
  await cmd(`mm items give MagTest ${ZAK}`)
  await sleep(1500)
  const z = Object.values(bot.entities).find(e => e.name === 'zombie')
  bot.setQuickBarSlot(bot.inventory.slots.findIndex(s => s) - 36 >= 0 ? bot.inventory.slots.findIndex(s => s) - 36 : 0)
  console.log('w rece:', bot.heldItem?.name, JSON.stringify(bot.heldItem?.components?.map(c => c.type)))
  if (z) await bot.lookAt(z.position.offset(0, 1.2 + (+(process.env.GORA||0)), 0), true)
  const hp0 = await cmd('data get entity @e[type=zombie,limit=1] Health')
  bot.activateItem(); const t0 = Date.now(); console.log('RZUCAM')
  await sleep(TRZYMAJ)
  bot.deactivateItem()
  await sleep(1200)
  console.log('HP przed:', hp0, '| po:', await cmd('data get entity @e[type=zombie,limit=1] Health'))
  console.log('spowolnienie:', await cmd('data get entity @e[type=zombie,limit=1] active_effects'))
  console.log('ogien/mroz:', await cmd('data get entity @e[type=zombie,limit=1] Fire'), '|', await cmd('data get entity @e[type=zombie,limit=1] TicksFrozen'))
  console.log('mana koniec:', await cmd('papi parse MagTest %mmocore_mana%'))
  console.log('czastki:', JSON.stringify(czastki)); dal.sort((a,b)=>a-b); console.log('zasieg strumienia [m]: min', dal[0]?.toFixed(2), 'med', dal[dal.length>>1]?.toFixed(2), 'p95', dal[Math.floor(dal.length*0.95)]?.toFixed(2), 'max', dal[dal.length-1]?.toFixed(2), 'n', dal.length); console.log('probki (wzgl. stop bota, kukla na +z):'); probki.forEach(p=>console.log(' ', JSON.stringify(p)))
  console.log('czat:\n  ' + czat.slice(-25).join('\n  '))
  bot.quit(); await rcon.end(); process.exit(0)
})().catch(e => { console.error('BLAD', e); process.exit(1) })
