import assert from 'node:assert/strict';
import { cpSync, mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync, spawnSync } from 'node:child_process';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPO_ROOT = path.resolve(__dirname, '../../..');
const AUDIT = path.join(REPO_ROOT, 'tools/qa/audit-mmoitems-runtime-load-pilot.mjs');

function withFixture(callback) {
  const tempRoot = mkdtempSync(path.join(os.tmpdir(), 'runtime-load-audit-'));
  try {
    for (const entry of ['docs', 'registry', 'build', 'content', 'tools']) {
      cpSync(path.join(REPO_ROOT, entry), path.join(tempRoot, entry), { recursive: true });
    }

    mkdirSync(path.join(tempRoot, 'MCMMORPG/plugins/MMOItems/item'), { recursive: true });
    writeFileSync(
      path.join(tempRoot, 'MCMMORPG/plugins/MMOItems/item/sword.yml'),
      readFileSync(path.join(REPO_ROOT, 'build/runtime/items/ashen_vanguard.yml'), 'utf8'),
      'utf8',
    );

    callback(tempRoot);
  } finally {
    rmSync(tempRoot, { recursive: true, force: true });
  }
}

function writeYaml(filePath, content) {
  mkdirSync(path.dirname(filePath), { recursive: true });
  writeFileSync(filePath, `${content.trim()}\n`, 'utf8');
}

function buildProof(buildId) {
  return [
    'schema_version: 1',
    'proof_kind: mmoitems-reload-boundary',
    'plugin: MMOItems',
    'environment: staging',
    `build_id: ${buildId}`,
    'target_file: MCMMORPG/plugins/MMOItems/item/sword.yml',
    'section_key: ASHEN_VANGUARD',
    'target_tuple: MMOItems:MCMMORPG/plugins/MMOItems/item/sword.yml#ASHEN_VANGUARD',
    'status: success',
    'captured_at: 2026-08-03T12:00:00Z',
  ].join('\n');
}

test('runtime load audit passes on allowed normalization', () =>
  withFixture((root) => {
    const buildId = 'staging-2026.08.03.1';
    const proofPath = path.join(root, 'evidence/runtime/reload-proof.yaml');
    const effectivePath = path.join(root, 'evidence/runtime/effective-runtime.yaml');
    const outputPath = path.join(root, 'evidence/runtime/runtime-load.json');

    writeYaml(proofPath, buildProof(buildId));
    writeYaml(
      effectivePath,
      [
        'ASHEN_VANGUARD:',
        '  base: SWORD',
        "  name: '&6Ashen Vanguard'",
        '  lore:',
        "    - '&7Forged for the vanguard that walks out of ash first.'",
        "    - '&8Pilot item generated by domain-18 content pipeline.'",
        "  attack-damage: '9.0'",
        "  attack-speed: '1.6'",
        '  required-level: 12',
        '  type: WEAPON',
      ].join('\n'),
    );

    const stdout = execFileSync(
      'node',
      [
        AUDIT,
        '--repo-root',
        root,
        '--build-id',
        buildId,
        '--reload-proof',
        proofPath,
        '--effective-runtime',
        effectivePath,
        '--output',
        outputPath,
      ],
      { cwd: root, encoding: 'utf8' },
    );

    const record = JSON.parse(readFileSync(outputPath, 'utf8'));
    assert.equal(record.verdict, 'pass');
    assert.equal(record.build_id, buildId);
    assert.match(stdout, /"verdict": "pass"/);
    assert.ok(record.assertions.includes('reverse-bijection-green'));
    assert.ok(record.assertions.includes('plugin-derived-whitelist-v1-within-normalization-contract'));
    assert.ok(record.assertions.includes('generated-projection-digest-match'));
    assert.ok(record.assertions.includes('committed-target-digest-match'));
  }));

test('runtime load audit fails on forbidden drift', () =>
  withFixture((root) => {
    const buildId = 'staging-2026.08.03.2';
    const proofPath = path.join(root, 'evidence/runtime/reload-proof.yaml');
    const effectivePath = path.join(root, 'evidence/runtime/effective-runtime.yaml');
    const outputPath = path.join(root, 'evidence/runtime/runtime-load.json');

    writeYaml(proofPath, buildProof(buildId));
    writeYaml(
      effectivePath,
      [
        'ASHEN_VANGUARD:',
        '  base: SWORD',
        "  name: '&6Ashen Vanguard'",
        '  lore:',
        "    - '&7Forged for the vanguard that walks out of ash first.'",
        "    - '&8Pilot item generated by domain-18 content pipeline.'",
        '  attack-damage: 11.0',
        '  attack-speed: 1.6',
        '  required-level: 12',
        '  tier: COMMON',
      ].join('\n'),
    );

    const result = spawnSync(
      'node',
      [
        AUDIT,
        '--repo-root',
        root,
        '--build-id',
        buildId,
        '--reload-proof',
        proofPath,
        '--effective-runtime',
        effectivePath,
        '--output',
        outputPath,
      ],
      { cwd: root, encoding: 'utf8' },
    );

    const record = JSON.parse(readFileSync(outputPath, 'utf8'));
    assert.equal(result.status, 1);
    assert.equal(record.verdict, 'fail');
    assert.ok(record.comparison.effective_runtime.failures.includes('generator-owned-value-changed:attack-damage'));
    assert.ok(record.comparison.effective_runtime.failures.includes('unknown-key-added:tier'));
  }));
