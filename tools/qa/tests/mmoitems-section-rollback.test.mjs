import assert from 'node:assert/strict';
import { cpSync, mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { execFileSync, spawnSync } from 'node:child_process';
import os from 'node:os';
import path from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPO_ROOT = path.resolve(__dirname, '../../..');
const ROLLBACK = path.join(REPO_ROOT, 'tools/qa/mmoitems-section-rollback.mjs');
const RELEASE_GATE = path.join(REPO_ROOT, 'tools/qa/evaluate-ashen-vanguard-release-gate.mjs');

function withFixture(callback) {
  const root = mkdtempSync(path.join(os.tmpdir(), 'mmoitems-section-rollback-'));
  try {
    for (const entry of ['docs', 'registry', 'tools']) {
      cpSync(path.join(REPO_ROOT, entry), path.join(root, entry), { recursive: true });
    }
    mkdirSync(path.join(root, 'MCMMORPG/plugins/MMOItems/item'), { recursive: true });
    callback(root);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

function writeTarget(root, ashenSection, extraSection = "LONG_SWORD:\n  base: SWORD\n") {
  writeFileSync(
    path.join(root, 'MCMMORPG/plugins/MMOItems/item/sword.yml'),
    `${extraSection}${ashenSection}`,
    'utf8',
  );
}

function baselineSection(nameLine = "  name: '&6Ashen Vanguard'\n") {
  return [
    'ASHEN_VANGUARD:',
    '  base: SWORD',
    nameLine.trimEnd(),
    '  lore:',
    "    - '&7Forged for the vanguard that walks out of ash first.'",
    "    - '&8Pilot item generated by domain-18 content pipeline.'",
    '  attack-damage: 9.0',
    '  attack-speed: 1.6',
    '  required-level: 12',
    '',
  ].join('\n');
}

function writeJson(filePath, value) {
  mkdirSync(path.dirname(filePath), { recursive: true });
  writeFileSync(filePath, `${JSON.stringify(value, null, 2)}\n`, 'utf8');
}

function runtimeEvidence(kind, overrides = {}) {
  return {
    schema_version: 1,
    evidence_id: `${kind}.item.weapon.sword.ashen_vanguard.staging-2026.08.03.2`,
    gate: kind,
    producer_domain: 'domain-18',
    producer_tool: 'fixture',
    verdict: 'pass',
    environment: 'staging',
    build_id: 'staging-2026.08.03.2',
    subject_id: 'item.weapon.sword.ashen_vanguard',
    content_type: 'item',
    source_path: 'content/items/weapons/ashen_vanguard.yaml',
    subject_digest: 'sha256:subject',
    dependency_digest: 'sha256:deps',
    runtime_plugin: 'MMOItems',
    target_file: 'MCMMORPG/plugins/MMOItems/item/sword.yml',
    section_key: 'ASHEN_VANGUARD',
    generated_projection_digest: 'sha256:projection',
    committed_target_digest: 'sha256:committed',
    effective_runtime_digest: 'sha256:effective',
    assertions: ['fixture'],
    captured_at: '2026-08-03T13:00:00Z',
    artifact_path: `evidence/runtime/${kind}.json`,
    ...overrides,
  };
}

test('capture-baseline writes only the authoritative section snapshot', () =>
  withFixture((root) => {
    writeTarget(root, baselineSection());
    execFileSync(
      'node',
      [ROLLBACK, 'capture-baseline', '--subject-id', 'item.weapon.sword.ashen_vanguard', '--build-id', 'staging-2026.08.03.2'],
      { cwd: root, encoding: 'utf8', env: { ...process.env, MC_CONTENT_ROOT: root } },
    );

    const baseline = readFileSync(
      path.join(root, 'evidence/runtime/ashen-vanguard/staging-2026.08.03.2/section-baseline.yaml'),
      'utf8',
    );
    assert.equal(baseline, baselineSection());
  }));

test('restore-section restores only ASHEN_VANGUARD and emits supported section-only proof', () =>
  withFixture((root) => {
    const originalExtra = "LONG_SWORD:\n  base: SWORD\n  name: '&fLong Sword'\n";
    writeTarget(root, baselineSection(), originalExtra);

    execFileSync(
      'node',
      [ROLLBACK, 'capture-baseline', '--subject-id', 'item.weapon.sword.ashen_vanguard', '--build-id', 'staging-2026.08.03.2'],
      { cwd: root, encoding: 'utf8', env: { ...process.env, MC_CONTENT_ROOT: root } },
    );

    writeTarget(root, baselineSection("  name: '&cMutated Vanguard'\n"), originalExtra);

    execFileSync(
      'node',
      [ROLLBACK, 'restore-section', '--subject-id', 'item.weapon.sword.ashen_vanguard', '--build-id', 'staging-2026.08.03.2'],
      { cwd: root, encoding: 'utf8', env: { ...process.env, MC_CONTENT_ROOT: root } },
    );

    const target = readFileSync(path.join(root, 'MCMMORPG/plugins/MMOItems/item/sword.yml'), 'utf8');
    const proof = readFileSync(
      path.join(root, 'evidence/runtime/ashen-vanguard/staging-2026.08.03.2/section-rollback-proof.yaml'),
      'utf8',
    );

    assert.ok(target.includes(originalExtra));
    assert.ok(target.includes("  name: '&6Ashen Vanguard'\n"));
    assert.ok(!target.includes('&cMutated Vanguard'));
    assert.match(proof, /tooling_status: supported/);
    assert.match(proof, /rollback_unit: section_only/);
    assert.match(proof, /status: success/);
  }));

test('restore-section fails closed when the target section is missing instead of falling back to whole-file restore', () =>
  withFixture((root) => {
    writeTarget(root, baselineSection());

    execFileSync(
      'node',
      [ROLLBACK, 'capture-baseline', '--subject-id', 'item.weapon.sword.ashen_vanguard', '--build-id', 'staging-2026.08.03.2'],
      { cwd: root, encoding: 'utf8', env: { ...process.env, MC_CONTENT_ROOT: root } },
    );

    writeFileSync(path.join(root, 'MCMMORPG/plugins/MMOItems/item/sword.yml'), "LONG_SWORD:\n  base: SWORD\n", 'utf8');

    const result = spawnSync(
      'node',
      [ROLLBACK, 'restore-section', '--subject-id', 'item.weapon.sword.ashen_vanguard', '--build-id', 'staging-2026.08.03.2'],
      { cwd: root, encoding: 'utf8', env: { ...process.env, MC_CONTENT_ROOT: root } },
    );

    assert.equal(result.status, 1);
    assert.match(result.stderr, /MISSING_SECTION/);
    assert.equal(readFileSync(path.join(root, 'MCMMORPG/plugins/MMOItems/item/sword.yml'), 'utf8'), "LONG_SWORD:\n  base: SWORD\n");
  }));

test('release gate reaches candidate when proof comes from real section-only rollback tooling', () =>
  withFixture((root) => {
    writeTarget(root, baselineSection());

    execFileSync(
      'node',
      [ROLLBACK, 'capture-baseline', '--subject-id', 'item.weapon.sword.ashen_vanguard', '--build-id', 'staging-2026.08.03.2'],
      { cwd: root, encoding: 'utf8', env: { ...process.env, MC_CONTENT_ROOT: root } },
    );

    writeTarget(root, baselineSection("  name: '&cMutated Vanguard'\n"));

    execFileSync(
      'node',
      [ROLLBACK, 'restore-section', '--subject-id', 'item.weapon.sword.ashen_vanguard', '--build-id', 'staging-2026.08.03.2'],
      { cwd: root, encoding: 'utf8', env: { ...process.env, MC_CONTENT_ROOT: root } },
    );

    writeJson(path.join(root, 'evidence/runtime/runtime-loaded.json'), runtimeEvidence('runtime_loaded'));
    writeJson(path.join(root, 'evidence/e2e/runtime-verified.json'), runtimeEvidence('runtime_verified'));

    const outputPath = path.join(root, 'evidence/runtime/release-candidate.json');
    execFileSync(
      'node',
      [
        RELEASE_GATE,
        '--runtime-loaded',
        path.join(root, 'evidence/runtime/runtime-loaded.json'),
        '--runtime-verified',
        path.join(root, 'evidence/e2e/runtime-verified.json'),
        '--rollback-proof',
        path.join(root, 'evidence/runtime/ashen-vanguard/staging-2026.08.03.2/section-rollback-proof.yaml'),
        '--output',
        outputPath,
      ],
      { cwd: root, encoding: 'utf8', env: { ...process.env, MC_CONTENT_ROOT: root } },
    );

    const record = JSON.parse(readFileSync(outputPath, 'utf8'));
    assert.equal(record.verdict, 'pass');
    assert.equal(record.release_status, 'candidate');
    assert.ok(record.assertions.includes('section-only-rollback-proof-confirmed'));
  }));
