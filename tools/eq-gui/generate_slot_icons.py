def render(key):
    rows = ART[key].strip("\n").split("\n")
    assert len(rows) == 16, (key, len(rows))
    for y, r in enumerate(rows):
        assert len(r) == 16, (key, y, len(r), r)

    def body(x, y):
        return 0 <= x < 16 and 0 <= y < 16 and rows[y][x] in "#o"

    im = Image.new("RGBA", (16, 16), NONE)
    px = im.load()
    for y in range(16):
        for x in range(16):
            ch = rows[y][x]
            if ch == '.':
                continue
            if ch == 'o':
                px[x, y] = DARK
                continue
            lit = (not body(x, y - 1)) or (not body(x - 1, y))
            shd = (not body(x, y + 1)) or (not body(x + 1, y))
            px[x, y] = EDGE if lit else (SHADOW if shd else BODY)
    return im


ARMOR = ['helmet', 'chestplate', 'leggings', 'boots', 'shield']
ACC = ['necklace', 'ring', 'gloves', 'belt', 'charm']

if __name__ == "__main__":
    armor_dir = sys.argv[1] if len(sys.argv) > 1 else "./armor"
    acc_dir = sys.argv[2] if len(sys.argv) > 2 else "./acc"
    os.makedirs(armor_dir, exist_ok=True)
    os.makedirs(acc_dir, exist_ok=True)
    for k in ARMOR:
        render(k).save(os.path.join(armor_dir, k + ".png"))
    for k in ACC:
        render(k).save(os.path.join(acc_dir, k + ".png"))
    print("zapisano %d ikon zbroi + %d ikon akcesoriow" % (len(ARMOR), len(ACC)))
