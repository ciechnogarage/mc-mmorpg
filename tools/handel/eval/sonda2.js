'use strict'
const L = require('/t/lib.js'); const { rconClient } = require('/t/rcon.js')
;(async () => {
  const rc = await rconClient()
  const [nA, nB] = (process.env.EVAL_NICKS || 'HdA1 HdB1').split(' ')
  for (const n of [nA, nB]) await rc.cmd(`deop ${n}`)
  const A = await L.wejdz(nA); const B = await L.wejdz(nB)
  const saldo = async n => L.strip(await rc.cmd(`papi parse ${n} %coretools_eco_dollar%`))
  for (const n of [nA, nB]) console.log('set', n, L.strip(await rc.cmd(`core-economy set dollar 100 ${n}`)))
  console.log(await rc.cmd(`mi give MATERIAL PROF_OAK_TIMBER ${nA} 20`))
  await L.sleep(1200)
  console.log('saldo', nA, await saldo(nA), nB, await saldo(nB))
  // A: Handel -> AH -> Wystaw
  await L.otworzHandel(A); await L.klik(A, 10); await L.czekajOkno(A, /Dom aukcyjny/)
  await L.klik(A, 49); let w = await L.czekajOkno(A, /Wystaw/)
  const inv = w.slots.findIndex((it, i) => i >= w.inventoryStart && it && /d[ęe]bowe/.test(L.nazwa(it)))
  console.log('drewno w oknie na slocie', inv, 'inventoryStart', w.inventoryStart)
  await L.klik(A, inv); await L.klik(A, 13)
  console.log('slot13:', A.currentWindow.slots[13] && L.nazwa(A.currentWindow.slots[13]), A.currentWindow.slots[13] && A.currentWindow.slots[13].count)
  await L.klik(A, 38); await L.sleep(200)          // "2"
  let c = A.currentWindow.slots[42]; console.log('confirm po cenie:', L.nazwa(c), '|', L.lore(c).join(' / '))
  await L.klik(A, 42); c = A.currentWindow.slots[42]; console.log('confirm uzbrojony:', L.nazwa(c))
  await L.klik(A, 42); await L.sleep(1500)
  console.log('A okno po wystawieniu:', L.tytul(A.currentWindow))
  console.log('saldo A po wystawieniu', await saldo(nA))
  // B: kupuje
  await L.otworzHandel(B); await L.klik(B, 10); w = await L.czekajOkno(B, /Dom aukcyjny/)
  const k = L.kafelki(w).find(x => /d[ęe]bowe/.test(x.nazwa)); console.log('oferta u B:', k)
  await L.klik(B, k.slot); w = await L.czekajOkno(B, /Kupno/); L.zrzut(w, 'Kupno')
  await L.klik(B, 40); console.log('kup uzbrojony:', L.nazwa(B.currentWindow.slots[40]), L.lore(B.currentWindow.slots[40]).join(' / '))
  await L.klik(B, 40); await L.sleep(1500)
  console.log('saldo A', await saldo(nA), 'B', await saldo(nB))
  console.log('B ma drewna:', B.inventory.items().filter(i => /d[ęe]bowe/.test(L.nazwa(i))).reduce((a, i) => a + i.count, 0))
  A.quit(); B.quit(); rc.close(); process.exit(0)
})().catch(e => { console.log('BLAD', e); process.exit(1) })
