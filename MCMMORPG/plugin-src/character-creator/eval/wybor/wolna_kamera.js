const w = require('./lib/w')
const R = new w.Results('wolna-kamera')
;(async () => {
  const off = w.logOffset()
  const bot = await w.connect(process.env.QA || 'WyborQA')
  const cams = []; bot._client.on('camera', p => cams.push(Date.now()))
  await w.sleep(7000)
  R.assert(!/wolna kamere/.test(w.logSince(off)), 'bez ruchu myszy: brak falszywego alarmu')
  const n = cams.length, t0 = Date.now()
  // Klient z wolna kamera wysyla obrot przy ruchu myszy — tu to samo pakietem.
  bot._client.write('look', { yaw: 37, pitch: 12, flags: { onGround: false, hasHorizontalCollision: false } })
  await w.sleep(1500)
  R.assert(/ma wolna kamere .* podpinam ponownie/.test(w.logSince(off)), 'obrot w scenie -> log "wolna kamera" i podpiecie', w.logSince(off).split('\n').filter(l => /kamer/.test(l)).join(' | '))
  R.assert(cams.some(t => t >= t0), 'po obrocie: nowy pakiet camera do klienta', `${n} -> ${cams.length}`)
  const o2 = w.logOffset(); await w.lpm(bot); await w.sleep(3000)
  R.assert(bot.game.gameMode !== 'spectator' || /PickStep/.test(w.logSince(o2)), 'LPM po podpieciu dziala (gra albo kreator)', bot.game.gameMode)
  await w.quit(bot)
  R.print(); console.log(`WYNIK: ${R.rows.length - R.failed}/${R.rows.length} PASS`); process.exit(R.failed)
})().catch(e => { R.print(); console.error('ERR', e); process.exit(99) })
